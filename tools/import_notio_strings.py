"""Takes interface texts in ten languages from the local Notio-Android resources (MIT, the same author) for the screens
FitEasy repeats after Notio: synchronization, protection, backup. Writes shared/src/com/fiteasy/shared/NotioStrings.kt.

Usage: python tools/import_notio_strings.py [path to Notio-Android]
The keys taken are listed in tools/notio_strings.txt, one resource name or prefix* per line.
"""
import re, sys, pathlib, xml.etree.ElementTree as ET

root = pathlib.Path(__file__).resolve().parent.parent
notio = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else r"D:\Notio-Android")
res = notio / "app" / "src" / "main" / "res"
languages = ["ru", "en", "be", "fr", "de", "es", "it", "zh", "ja", "ko"]
folders = {"en": "values", "zh": "values-zh-rCN"}


def load(language):
    folder = res / folders.get(language, "values-" + language)
    if not folder.is_dir():
        folder = next(p for p in res.iterdir() if p.name.startswith("values-" + language))
    texts = {}
    for file in sorted(folder.glob("*.xml")):
        for node in ET.parse(file).getroot().findall("string"):
            texts[node.get("name")] = "".join(node.itertext())
    return texts


def clean(text):
    text = text.strip()
    if len(text) >= 2 and text[0] == '"' and text[-1] == '"':
        text = text[1:-1]
    text = text.replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"').replace("\\@", "@").replace("\\?", "?")
    text = re.sub(r"%(\d)\$[sd]", lambda m: "{" + str(int(m.group(1)) - 1) + "}", text).replace("%%", "%")
    return text.replace("Notio", "FitEasy")


def kotlin(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n") + '"'


wanted = [line.strip() for line in (root / "tools" / "notio_strings.txt").read_text(encoding="utf-8").splitlines() if line.strip() and not line.startswith("#")]
tables = {language: load(language) for language in languages}
names = []
for pattern in wanted:
    found = sorted(n for n in tables["ru"] if (n.startswith(pattern[:-1]) if pattern.endswith("*") else n == pattern))
    if not found:
        raise SystemExit("No Notio text for " + pattern)
    names += [n for n in found if n not in names]

keys, rows = [], {}
for name in names:
    russian = clean(tables["ru"][name])
    keys.append((name, russian))
    rows.setdefault(russian, [clean(tables[l].get(name, tables["en"][name])) for l in languages[1:]])

out = ["package com.fiteasy.shared", "",
       "// Generated by tools/import_notio_strings.py from Notio-Android string resources (MIT, Copyright (c) 2026 vibic777). Do not edit by hand.",
       "/** Notio resource name → the Russian text that is the key of every FitEasy dictionary. */",
       "internal val notioKeys:Map<String,String> = mapOf("]
out += ["    " + kotlin(name) + " to " + kotlin(text) + "," for name, text in keys]
out += [")", "/** Russian text → en, be, fr, de, es, it, zh, ja, ko. */", "internal val notioRows:Map<String,Array<String>> = mapOf("]
out += ["    " + kotlin(russian) + " to arrayOf(" + ",".join(kotlin(v) for v in values) + ")," for russian, values in rows.items()]
out += [")", ""]
(root / "shared" / "src" / "com" / "fiteasy" / "shared" / "NotioStrings.kt").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(len(keys), "keys,", len(rows), "texts")
